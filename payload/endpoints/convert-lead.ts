import { commitTransaction, initTransaction, killTransaction, type Endpoint } from 'payload';

const relationId = (value: unknown) =>
  value && typeof value === 'object' ? (value as { id: number }).id : (value as number | null | undefined);

/**
 * POST /api/leads/:id/convert
 * Creates an application from the lead, links it and marks the lead Converted, in one transaction.
 * Access rules apply: staff can only convert leads assigned to them.
 */
export const convertLead: Endpoint = {
  path: '/:id/convert',
  method: 'post',
  handler: async (req) => {
    if (!req.user) return Response.json({ error: 'Please log in again.' }, { status: 401 });
    const id = String(req.routeParams?.id ?? '');
    const lead = await req.payload
      .findByID({ collection: 'leads', id, depth: 0, req, overrideAccess: false })
      .catch(() => null);
    if (!lead) return Response.json({ error: 'Lead not found.' }, { status: 404 });

    // Already converted: send them to the existing application instead of creating a duplicate
    const existing = relationId(lead.application);
    if (existing) return Response.json({ id: existing, existing: true });

    const { docs: [country] } = await req.payload.find({
      collection: 'countries', depth: 0, limit: 1, req,
      where: { name: { equals: lead.interestedCountry?.trim() ?? '' } },
    });
    if (!country) {
      return Response.json(
        { error: `"${lead.interestedCountry || 'No country'}" is not one of your destinations. Correct the lead's country of interest, save, and try again.` },
        { status: 400 },
      );
    }

    const shouldCommit = await initTransaction(req);
    try {
      const application = await req.payload.create({
        collection: 'applications', req, overrideAccess: false,
        data: {
          reference: '', // generated by the collection hook
          studentName: lead.name,
          email: lead.email,
          phone: lead.phone,
          country: country.id,
          message: lead.message,
          sourcePage: lead.sourcePage,
          status: 'documents-required',
          // Admins keep the lead's owner; staff become the owner automatically
          ...(req.user.role === 'admin' && lead.assignedTo ? { assignedTo: relationId(lead.assignedTo) } : {}),
        },
      });
      await req.payload.update({
        collection: 'leads', id, req, overrideAccess: false,
        data: { application: application.id, status: 'application-started' },
      });
      if (shouldCommit) await commitTransaction(req);
      return Response.json({ id: application.id }, { status: 201 });
    } catch (error) {
      await killTransaction(req);
      req.payload.logger.error({ err: error, msg: 'Lead conversion failed' });
      return Response.json({ error: 'Could not create the application. Please try again.' }, { status: 500 });
    }
  },
};
